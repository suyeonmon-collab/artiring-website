import { cpSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'characters');
const destDir = join(root, 'public/characters');

mkdirSync(destDir, { recursive: true });

const assets = {};

for (const file of readdirSync(srcDir).filter((name) => name.endsWith('.glb'))) {
  const key = file.replace(/\.glb$/, '');
  const srcPath = join(srcDir, file);
  const destPath = join(destDir, file);

  cpSync(srcPath, destPath);

  const hash = createHash('md5').update(readFileSync(srcPath)).digest('hex').slice(0, 8);
  assets[key] = { path: `/characters/${file}`, version: hash };
}

const output = `// Auto-generated by scripts/sync-characters.mjs
export const CHARACTER_ASSETS = ${JSON.stringify(assets, null, 2)};

export function characterSrc(key) {
  const asset = CHARACTER_ASSETS[key];
  if (!asset) throw new Error(\`Unknown character asset: \${key}\`);
  return \`\${asset.path}?v=\${asset.version}\`;
}
`;

writeFileSync(join(root, 'lib/characterAssets.js'), output);
console.log('Synced character GLB assets:', Object.keys(assets).join(', '));
